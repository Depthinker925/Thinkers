const WEEKDAY_NAMES: Record<Locale, string[]> = {
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
  zh: ["日", "一", "二", "三", "四", "五", "六"],
};

const MONTH_NAMES = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function monthLabel(locale: Locale, year: number, month: number): string {
  if (locale === "zh") return `${year} 年 ${month + 1} 月`;
  return `${MONTH_NAMES[month]} ${year}`;
}

let lang: Locale = "en";

function detectLocale(): Locale {
  const raw = getLanguage() || window.navigator.language || "en";
  return raw.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function initLocale(): void {
  lang = detectLocale();
}

export function currentLocale(): Locale {
  return lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = lang === "zh" ? ZH : EN;
  const template = dict[key] ?? EN[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function weekdays(): string[] {
  return WEEKDAY_NAMES[lang];
}

export function monthTitle(year: number, month: number): string {
  return monthLabel(lang, year, month);
}
